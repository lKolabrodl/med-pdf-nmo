import { describe, expect, it } from "vitest";
import { resolveNegationPairClause } from "../src/predictor/scorers/negation-pair.js";

function answers(values: string[]) {
  return values.map((text, index) => ({ id: String.fromCharCode(65 + index), text }));
}

function resolve(question: string, values: string[], fragments: string[]) {
  return resolveNegationPairClause({
    mode: "single",
    question,
    answers: answers(values),
    fragments: fragments.map((text, index) => ({ page: index + 1, text })),
  });
}

describe("negation-paired option family", () => {
  const values = [
    "\u043d\u0435 \u043f\u043e\u0437\u0432\u043e\u043b\u044f\u0435\u0442 \u0434\u043e\u0441\u0442\u043e\u0432\u0435\u0440\u043d\u043e \u043e\u0442\u043b\u0438\u0447\u0438\u0442\u044c \u0431\u043e\u043b\u0435\u0437\u043d\u044c \u0430\u043b\u044c\u0444\u0430 \u043e\u0442 \u0431\u043e\u043b\u0435\u0437\u043d\u0438 \u0431\u0435\u0442\u0430",
    "\u043f\u0440\u0438\u043c\u0435\u043d\u044f\u0435\u0442\u0441\u044f \u0434\u043b\u044f \u0434\u0440\u0443\u0433\u043e\u0439 \u0446\u0435\u043b\u0438",
    "\u043f\u043e\u0437\u0432\u043e\u043b\u044f\u0435\u0442 \u0434\u043e\u0441\u0442\u043e\u0432\u0435\u0440\u043d\u043e \u043e\u0442\u043b\u0438\u0447\u0438\u0442\u044c \u0431\u043e\u043b\u0435\u0437\u043d\u044c \u0430\u043b\u044c\u0444\u0430 \u043e\u0442 \u0431\u043e\u043b\u0435\u0437\u043d\u0438 \u0431\u0435\u0442\u0430",
  ];

  it("selects the negative member when negation is attached to the shared predicate", () => {
    expect(
      resolve(
        "\u0414\u0438\u0430\u0433\u043d\u043e\u0441\u0442\u0438\u0447\u0435\u0441\u043a\u0430\u044f \u043f\u0440\u043e\u0431\u0430 \u043f\u0440\u0438 \u0431\u043e\u043b\u0435\u0437\u043d\u0438 \u0430\u043b\u044c\u0444\u0430",
        values,
        ["\u0414\u0438\u0430\u0433\u043d\u043e\u0441\u0442\u0438\u0447\u0435\u0441\u043a\u0430\u044f \u043f\u0440\u043e\u0431\u0430 \u043d\u0435 \u043f\u043e\u0437\u0432\u043e\u043b\u044f\u0435\u0442 \u0434\u043e\u0441\u0442\u043e\u0432\u0435\u0440\u043d\u043e \u043e\u0442\u043b\u0438\u0447\u0438\u0442\u044c \u0431\u043e\u043b\u0435\u0437\u043d\u044c \u0430\u043b\u044c\u0444\u0430 \u043e\u0442 \u0431\u043e\u043b\u0435\u0437\u043d\u0438 \u0431\u0435\u0442\u0430."],
      )?.answerId,
    ).toBe("A");
  });

  it("selects the positive member when the shared predicate is affirmative", () => {
    expect(
      resolve(
        "\u0414\u0438\u0430\u0433\u043d\u043e\u0441\u0442\u0438\u0447\u0435\u0441\u043a\u0430\u044f \u043f\u0440\u043e\u0431\u0430 \u043f\u0440\u0438 \u0431\u043e\u043b\u0435\u0437\u043d\u0438 \u0430\u043b\u044c\u0444\u0430",
        values,
        ["\u0414\u0438\u0430\u0433\u043d\u043e\u0441\u0442\u0438\u0447\u0435\u0441\u043a\u0430\u044f \u043f\u0440\u043e\u0431\u0430 \u043f\u043e\u0437\u0432\u043e\u043b\u044f\u0435\u0442 \u0434\u043e\u0441\u0442\u043e\u0432\u0435\u0440\u043d\u043e \u043e\u0442\u043b\u0438\u0447\u0438\u0442\u044c \u0431\u043e\u043b\u0435\u0437\u043d\u044c \u0430\u043b\u044c\u0444\u0430 \u043e\u0442 \u0431\u043e\u043b\u0435\u0437\u043d\u0438 \u0431\u0435\u0442\u0430."],
      )?.answerId,
    ).toBe("C");
  });

  it("abstains when focus-compatible fragments disagree on polarity", () => {
    expect(
      resolve(
        "\u0414\u0438\u0430\u0433\u043d\u043e\u0441\u0442\u0438\u0447\u0435\u0441\u043a\u0430\u044f \u043f\u0440\u043e\u0431\u0430 \u043f\u0440\u0438 \u0431\u043e\u043b\u0435\u0437\u043d\u0438 \u0430\u043b\u044c\u0444\u0430",
        values,
        [
          "\u0414\u0438\u0430\u0433\u043d\u043e\u0441\u0442\u0438\u0447\u0435\u0441\u043a\u0430\u044f \u043f\u0440\u043e\u0431\u0430 \u043d\u0435 \u043f\u043e\u0437\u0432\u043e\u043b\u044f\u0435\u0442 \u0434\u043e\u0441\u0442\u043e\u0432\u0435\u0440\u043d\u043e \u043e\u0442\u043b\u0438\u0447\u0438\u0442\u044c \u0431\u043e\u043b\u0435\u0437\u043d\u044c \u0430\u043b\u044c\u0444\u0430 \u043e\u0442 \u0431\u043e\u043b\u0435\u0437\u043d\u0438 \u0431\u0435\u0442\u0430.",
          "\u0414\u0438\u0430\u0433\u043d\u043e\u0441\u0442\u0438\u0447\u0435\u0441\u043a\u0430\u044f \u043f\u0440\u043e\u0431\u0430 \u043f\u043e\u0437\u0432\u043e\u043b\u044f\u0435\u0442 \u0434\u043e\u0441\u0442\u043e\u0432\u0435\u0440\u043d\u043e \u043e\u0442\u043b\u0438\u0447\u0438\u0442\u044c \u0431\u043e\u043b\u0435\u0437\u043d\u044c \u0430\u043b\u044c\u0444\u0430 \u043e\u0442 \u0431\u043e\u043b\u0435\u0437\u043d\u0438 \u0431\u0435\u0442\u0430.",
        ],
      ),
    ).toBeNull();
  });

  it("does not attach an unrelated negation to a later positive predicate", () => {
    expect(
      resolve(
        "\u0414\u0438\u0430\u0433\u043d\u043e\u0441\u0442\u0438\u0447\u0435\u0441\u043a\u0430\u044f \u043f\u0440\u043e\u0431\u0430 \u043f\u0440\u0438 \u0431\u043e\u043b\u0435\u0437\u043d\u0438 \u0430\u043b\u044c\u0444\u0430",
        values,
        ["\u0414\u0438\u0430\u0433\u043d\u043e\u0441\u0442\u0438\u0447\u0435\u0441\u043a\u0430\u044f \u043f\u0440\u043e\u0431\u0430 \u043d\u0435 \u0432\u044b\u0437\u044b\u0432\u0430\u0435\u0442 \u0431\u043e\u043b\u0438 \u0438 \u043f\u043e\u0437\u0432\u043e\u043b\u044f\u0435\u0442 \u0434\u043e\u0441\u0442\u043e\u0432\u0435\u0440\u043d\u043e \u043e\u0442\u043b\u0438\u0447\u0438\u0442\u044c \u0431\u043e\u043b\u0435\u0437\u043d\u044c \u0430\u043b\u044c\u0444\u0430 \u043e\u0442 \u0431\u043e\u043b\u0435\u0437\u043d\u0438 \u0431\u0435\u0442\u0430."],
      )?.answerId,
    ).toBe("C");
  });
});
